import os
from docx import Document
from docx.shared import Pt, Inches, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

def create_docx(filename):
    doc = Document()
    
    # Define styles for normal text
    style = doc.styles['Normal']
    font = style.font
    font.name = 'Arial Unicode MS'
    font.size = Pt(12)
    
    # Title
    title = doc.add_heading('शोधसारः (Abstract)', level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_run = title.runs[0]
    title_run.font.name = 'Arial Unicode MS'
    
    # Header
    heading = doc.add_heading('शीर्षकम् : वेदान्ते विधिविचारसमीक्षणम्', level=1)
    heading.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for r in heading.runs:
        r.font.name = 'Arial Unicode MS'
    
    doc.add_paragraph() # Spacing

    content = [
        "भारतीयदर्शनप्रस्थानेषु मीमांसावेदान्तशास्त्रयोः विधिविचारः महते विवादाय कल्पते। तत्र पूर्वमीमांसकैस्तावत् सम्पूर्णस्यापि वेदराशेः क्रियार्थकत्वमङ्गीकृत्य ‘आम्नायस्य क्रियार्थत्वात्’ इति न्यायेन वेदान्तवाक्यानामपि विधिप्रकरणे एव तात्पर्यं कल्पितम्। तेषामयमाशयो यत् वेदान्तवाक्यानि न स्वातन्त्र्येण सिद्धवस्तु बोधयितुमीशते, अपि तूपಾಸनादिविधिशेषत्वेनैव तेषां प्रामाण्यमिति।",
        "अत्रोत्तरमीमांसायां (अद्वैतवेदान्ते) भगवत्पादाचार्यैः 'तत्तु समन्वयात्' (ब्र. सू. १.१.४) इति सूत्रभाष्ये सिद्धान्तितं यद् ज्ञानस्य वस्तुतन्त्रत्वान्न तत्र पुरुषव्यापारस्य लवलेशोऽप्यपेक्ष्यते। यतो हि 'कर्तुमकर्तुमन्यथा वा कर्तुं' शक्यमानं पुरुषतन्त्रं कर्मैव विधिविषयो भवति, न तु नित्यसिद्धं ब्रह्म। ततश्च वेदान्तवाक्यानामज्ञाननिवर्तकत्वमेव, न तु विधायकत्वम्। 'आत्मा वा अरे द्रष्टव्यः' इत्यादिश्रुतिषु दृश्यमानो विध्याभासोऽपि न अपूर्वविधिपरः, अपि त्वनात्मदर्शनात् परावृत्य आत्मदर्शनप्रवृत्तये नियमपरः परिसङ्ख्यापरो वा इति शारीरकमीमांसायामुपपादितम्।",
        "किञ्च, मोक्षस्य नित्यसिद्धस्वरूपत्वान्न तत्रोत्पाद्याप्यविकार्यसंस्कार्यरूपाश्चतुर्विधा अपि कर्मव्यापाराः सम्भवन्ति। मोक्षस्य कर्मसाध्यत्वे तस्यानित्यत्वप्रसङ्गो दुर्वारः स्यात्। मीमांसकैर्यथा धर्मप्रतिपत्तये विध्यधीना शाब्दी भावना स्वीक्रियते, न तथा वेदान्ते। अत्र तु तत्त्वमस्यादिमहावाक्यजन्यया अखण्डाकारवृत्त्यैव साक्षान्मोक्षः सिद्ध्यति, यत्र विधेः कोऽप्युपयोगो नास्ति।",
        "अर्वाचीनवेदान्तिष्वपि श्रवणादिविधिविषये मतभेदो जागत्येव। विवरणकाराः श्रवणादौ अपूर्वविधिं समर्थयन्ते, भामतीकारास्तु अन्वयव्यतिरेकाभ्यामेव श्रवणादीनां साधनत्वोपपत्तेः तत्र विध्यभावं मन्यन्ते।",
        "प्रकृते शोधपत्रे पूर्वोत्तरमीमांसयोर्विधिविषयकमतभेदानां सयुक्तिकं समीक्षणं विहितमस्ति। सिद्धान्ततस्तु चित्तशुद्ध्यर्थमुपासनादौ विधेरुपयोगे सत्यपि परमार्थतत्त्वज्ञाने मोक्षसाधने वा विधेः प्रवेशः सर्वथा नास्त्येवेति निष्कर्षः।"
    ]
    
    for text in content:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.first_line_indent = Inches(0.25)
        p.paragraph_format.space_after = Pt(12)
        run = p.add_run(text)
        run.font.name = 'Arial Unicode MS'

    # Keywords
    p_kw_h = doc.add_heading('मुख्यशब्दाः (Keywords):', level=2)
    for r in p_kw_h.runs: r.font.name = 'Arial Unicode MS'
    
    p_kw = doc.add_paragraph()
    run = p_kw.add_run('विधिविचारः, अद्वैतवेदान्तः, पूर्वमीमांसा, अपूर्वविधिः, वस्तुतन्त्रम्, शारीरकमीमांसा, अखण्डाकारवृत्तिः।')
    run.font.name = 'Arial Unicode MS'
    
    doc.add_paragraph()

    # References
    p_ref_h = doc.add_heading('सन्दर्भाः (References)', level=2)
    for r in p_ref_h.runs: r.font.name = 'Arial Unicode MS'
    
    refs = [
        '१. ब्रह्मसूत्रशाङ्करभाष्यम् - समन्वयाधिकरणम् (सूत्रम् १.१.४ "तत्तु समन्वयात्"), निर्णयसागर-प्रेस, मुम्बई (पृष्ठाङ्काः: १३४-१४५)।',
        '२. भामती (वाचस्पतिमिश्रकृता) - १.१.४ सूत्रभाष्योपरि, चौखम्बा-संस्कृत-संस्थानम्, वाराणसी (पृष्ठाङ्काः: ११०-११८)।',
        '३. पञ्चपादिकाविवरणम् (प्रकाशामनमुनिकृतम्) - प्रथमवर्णकम्, मद्रास-विश्वविद्यालय-संस्करणम् (पृष्ठाङ्काः: ८५-९५)।',
        '४. वेदान्तपरिभाषा (धर्मराजार्ध्वरीन्द्रकृता) - आगमपरिच्छेदः, रामकृष्णमठ-संस्करणम् (पृष्ठाङ्काः: १५२-१५७)।',
        '५. पूर्वमीमांसासूत्रम् (जैमिनिकृतम्) - १.२.१ ("आम्नायस्य क्रियार्थत्वात्..."), आनन्दाश्रम-मुद्रणालयः, पुणे (पृष्ठाङ्कः: २५)।'
    ]
    
    for ref in refs:
        p = doc.add_paragraph(style='List Number')
        run = p.add_run(ref)
        run.font.name = 'Arial Unicode MS'
        
    doc.save(filename)

